#!/usr/bin/env bash
# Copies the data of the app from risale-i-nur-kulliyati: the books in their original Latin letters
# (not the -osmanlica/-ete copies, the app writes those live), their images, the Ottoman dictionary
# and the ETE letter table. And the fonts of the books.
#
#   scripts/sync-data.sh [path to risale-i-nur-kulliyati] [fonts directory]
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
RNK=${1:-$ROOT/../risale-i-nur-kulliyati}
FONTS=${2:-"/mnt/c/Users/EOUXJ/Downloads/archive/Document fonts/Document fonts"}

# slug (the book names of the links, tools/footnotes.py BOOKS) and the book's HTML
BOOKS=(
  "asayi_musa|Asa-yı Musa/Asa-yı Musa.html"
  "barla_lahikasi|Barla Lahikası/Barla Lahikası.html"
  "emirdag_lahikasi|Emirdag Lahikasi/Emirdag Lahikası.html"
  "eski_said_donemi|Eski Said Donemi Eserleri/Eski Said Donemi Eserleri.html"
  "hizmet_rehberi|Hizmet Rehberi/Hizmet Rehberi.html"
  "iman_kufur|iman-kufur muvazeneleri/Iman ve Kufur Muvazeneleri.html"
  "isaretulicaz|isaratul-icaz/isaratul-icaz.html"
  "kastamonu_lahikasi|Kastamonu_Lahikasi/kastamonu_lahikasi.html"
  "lemalar|Lemalar/Lemalar.html"
  "mektubat|Mektubat/Mektubat.html"
  "mesnevi_nuriye|Mesnevi-i Nuriye/Mesnevi-i Nuriye.html"
  "muhakemat|Muhakemat/Muhakemat.html"
  "sikkei_tasdiki_gaybi|Sikke-i Tasdik-i Gaybi/Sikke-i Tasdik-i Gaybi.html"
  "sozler|Sozler/Sozler.html"
  "sualar|Sualar/Sualar.html"
  "tarihceihayat|Tarihce-i Hayat/Tarihce-i Hayat.html"
  "tilsimlar|Tılsımlar/Tılsımlar.html"
  "zulfikar|Zulfikar/Zulfikar.html"
  "fihrist|Fihrist Risalesi/Fihrist Risalesi.html"
  "hizbul_kuran|Hizbul Kuran/Hizbul Kuran.html"
)

rm -rf "$ROOT/data/books" "$ROOT/public/resim"
mkdir -p "$ROOT/data/books" "$ROOT/public/resim" "$ROOT/public/fonts"
for entry in "${BOOKS[@]}"; do
  slug=${entry%%|*}
  file=$RNK/${entry#*|}
  cp "$file" "$ROOT/data/books/$slug.html"
  # the images of a book are in <Book>-web-resources/image next to it
  for res in "$(dirname "$file")"/*-web-resources; do
    [ -d "$res/image" ] || continue
    mkdir -p "$ROOT/public/resim/$slug"
    cp "$res/image/"* "$ROOT/public/resim/$slug/"
  done
done

cp "$RNK/tools/osmanlica/sozluk.tsv" "$ROOT/data/sozluk.tsv"
cp "$RNK/tools/ete/cetvel.tsv" "$ROOT/data/cetvel.tsv"

# the typefaces of the headlines and of the words set apart (css/yazi.css), its print pixels in the
# reader's unit (--px, app/kitap.css)
{
  echo "/* Generated by scripts/sync-data.sh from risale-i-nur-kulliyati css/yazi.css. Do not edit. */"
  sed -E -e 's/([0-9]+(\.[0-9]+)?)px/calc(\1 * var(--px))/g' -e 's/"Seherazade TR Quran"/"Seherazade Quran"/g' "$RNK/css/yazi.css"
} > "$ROOT/app/yazi.css"

cp "$RNK/css/fonts/Hüsrev Hatti Osmanlica.ttf" "$ROOT/public/fonts/HusrevHattiOsmanlica.ttf"
if [ -d "$FONTS" ]; then
  for f in "$FONTS"/*.ttf "$FONTS"/*.otf; do
    cp "$f" "$ROOT/public/fonts/$(basename "$f" | tr -d ' ')"
  done
fi

echo "books: $(ls "$ROOT/data/books" | wc -l), images: $(find "$ROOT/public/resim" -type f | wc -l), fonts: $(ls "$ROOT/public/fonts" | wc -l)"
